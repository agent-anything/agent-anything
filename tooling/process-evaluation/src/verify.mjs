import assert from "node:assert/strict";
import {mkdtemp, readFile, symlink, mkdir, writeFile} from "node:fs/promises";
import {join} from "node:path";
import {tmpdir} from "node:os";
import {processPlan, runDesktopProcessTrial} from "./process-runner.mjs";
import {readBranchFile, createProcessStore} from "./process-storage.mjs";
import {assertProcessBranchIsolation} from "@agent-anything/evaluation/process";

const root = await mkdtemp(join(tmpdir(), "helarc-process-trials-"));
console.log(`Process evaluation evidence: ${root}`);
const firstOwner = await createProcessStore(join(root, "ownership")), secondOwner = await createProcessStore(join(root, "ownership"));
const lease = await firstOwner.claim();
await assert.rejects(secondOwner.claim(), /already_owned/);
await lease.release(); await (await secondOwner.claim()).release();
const first = processPlan("trial-resume", {initialEffect: true});
const second = processPlan("trial-child", {child: true});
assertProcessBranchIsolation([first.branch, second.branch]);
const directory = join(root, "resume");
const interrupted = await runDesktopProcessTrial({directory, plan: first, interruptAfterEffect: true});
assert.equal(interrupted.report.execution, "interrupted", JSON.stringify(interrupted));
assert.equal(interrupted.report.cleanup.status, "cleaned");
const original = JSON.parse(await readFile(join(directory, "target-execution.json"), "utf8"));
const completed = await runDesktopProcessTrial({directory, plan: first});
assert.equal(completed.report.execution, "completed", JSON.stringify(completed));
assert.equal(completed.report.cleanup.status, "cleaned");
assert.equal(await readFile(join(directory, "workspace", "effect.txt"), "utf8"), "yx");
await assert.rejects(readBranchFile(directory, "workspace/effect.txt", 1), /source_bound/);
assert.equal(JSON.parse(await readFile(join(directory, "target-execution.json"), "utf8")).runId, original.runId);
assert(completed.report.conclusions.every(value => value.verdict === "conforms"), JSON.stringify(completed));
console.log("Original Trial resumed through Electron/SQLite with one effect, complete capture and confirmed cleanup.");
const childDirectory = join(root, "child");
const childInterrupted = await runDesktopProcessTrial({directory: childDirectory, plan: second, interruptAfterEffect: true});
assert.equal(childInterrupted.report.execution, "interrupted", JSON.stringify(childInterrupted));
const childBoundary = JSON.parse(await readFile(join(childDirectory, "interruption.json"), "utf8"));
assert.notEqual(childBoundary.effectRunId, childBoundary.runId, "The accepted effect must belong to the real Child");
const delegated = await runDesktopProcessTrial({directory: childDirectory, plan: second});
assert.equal(delegated.report.execution, "completed", JSON.stringify(delegated));
const childOutcome = JSON.parse(await readFile(join(childDirectory, "target-result.json"), "utf8"));
const capture = JSON.parse(await readFile(join(childDirectory, childOutcome.captureExport.file), "utf8"));
assert.equal(capture.members.length, 2, "Real Agent Tool must create a Child");
assert(capture.members.every(member => member.status === "completed"));
assert.equal(capture.rootRunId, childBoundary.runId);
assert(capture.members.some(member => member.runId === childBoundary.effectRunId));
assert.equal(await readFile(join(childDirectory, "workspace", "effect.txt"), "utf8"), "x");
assert(delegated.report.conclusions.every(value => value.verdict === "conforms"), JSON.stringify(delegated));
await assert.rejects(readBranchFile(directory, "../child/workspace/effect.txt"), /cross_branch/);
await symlink(join(childDirectory, "workspace"), join(directory, "foreign"), process.platform === "win32" ? "junction" : "dir");
await assert.rejects(readBranchFile(directory, "foreign/effect.txt"), /cross_branch/);
console.log("Independent Child Trial and both direct/junction cross-branch capture denials passed.");
const foreignFile = join(childDirectory, "workspace", "private-result.txt");
await writeFile(foreignFile, "BRANCH_PRIVATE_RESULT_c5a2");
const foreignDirectory = join(root, "foreign-read");
const foreign = await runDesktopProcessTrial({directory: foreignDirectory, plan: processPlan("trial-foreign-read", {foreignReadPath: foreignFile})});
assert.equal(foreign.report.execution, "completed", JSON.stringify(foreign));
const wire = await readFile(join(foreignDirectory, "provider-requests.jsonl"), "utf8");
assert(!wire.includes("BRANCH_PRIVATE_RESULT_c5a2"), "Foreign content must not be delivered through a real Read Tool");
const toolResults = wire.trim().split("\n").map(JSON.parse).flatMap(request => request.messages.filter(message => message.role === "tool").map(message => JSON.parse(message.content)));
assert(toolResults.some(result => result.content?.failure?.code === "absolute_path_not_allowed"), "The real Tool path boundary must reject outside-workspace access");
const invalid = await runDesktopProcessTrial({directory: join(root, "invalid"), plan: processPlan("trial-invalid"), corruptReceipt: true});
assert.equal(invalid.report.execution, "failed");
assert.equal(invalid.report.conclusions.find(value => value.claim === "effect_once").verdict, "insufficient_evidence");
await assert.rejects(readFile(join(root, "invalid", "target-execution.json")), {code: "ENOENT"});
const timeout = await runDesktopProcessTrial({directory: join(root, "timeout"), plan: processPlan("trial-timeout", {wait: true}), timeoutMs: 15000});
assert.equal(timeout.report.execution, "timed_out", JSON.stringify(timeout));
assert.equal(timeout.report.cleanup.status, "cleaned", JSON.stringify(timeout));
const questionDirectory = join(root, "question");
const question = await runDesktopProcessTrial({directory: questionDirectory, plan: processPlan("trial-question", {question: true}), timeoutMs: 15000});
assert.equal(question.report.execution, "timed_out", JSON.stringify(question));
assert.equal(question.report.cleanup.status, "cleaned", JSON.stringify(question));
const interaction = (await readFile(join(questionDirectory, "interaction-events.jsonl"), "utf8")).trim().split("\n").map(JSON.parse);
assert.equal(interaction.length, 1); assert.equal(interaction[0].request.protocol.kind, "clarification");
assert.equal(interaction[0].disposition, "awaiting_external_input");
await assert.rejects(readFile(join(questionDirectory, "approval-failure.json")), {code: "ENOENT"});
await assert.rejects(readFile(join(questionDirectory, "approval-events.jsonl")), {code: "ENOENT"});
const questionEvidence = JSON.parse(await readFile(join(questionDirectory, `${question.report.capture.ref.id.replace(":", "-")}.json`), "utf8"));
assert.deepEqual(questionEvidence.interactions, interaction);
assert.equal(questionEvidence.effects.count, 0);
assert(questionEvidence.execution.members.every(member => member.status === "cancelled"));
const next = await runDesktopProcessTrial({directory: join(root, "after-timeout"), plan: processPlan("trial-after-timeout")});
assert.equal(next.report.execution, "completed", JSON.stringify(next));
assert.equal(next.report.cleanup.status, "cleaned");
assert.equal(await readFile(join(root, "after-timeout", "workspace", "effect.txt"), "utf8"), "x");
console.log("Rejected start, unanswered clarification, bounded timeout, joined cleanup and immediate next Trial passed.");
console.log(`Batch 6 process foundation passed. Reports and original evidence retained: ${root}`);
